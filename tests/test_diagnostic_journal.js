const assert = require('node:assert/strict');
const journal = require('../src/js/app/diagnostic_journal.js');

assert.equal(journal.capacity, 300);
assert.equal(journal.settings().diagnostics, false);
assert.equal(journal.enabled('general'), true);
assert.equal(journal.capture('debug hidden', 'DEBUG', 'diagnostics'), null);
journal.capture('Started');
assert.equal(journal.entries().length, 1);
assert.equal(journal.entries()[0].category, 'general');
journal.setEnabled('import_export', false);
assert.equal(journal.capture('Import failed', 'ERROR', 'import_export'), null);
assert.equal(journal.entries().length, 1);
journal.setEnabled('import_export', true);
assert.equal(journal.capture('Import failed', 'ERROR', 'import_export').category, 'import_export');
journal.setEnabled('runtime', false);
assert.equal(journal.capture('Worker failed', 'ERROR', 'runtime'), null);
assert.ok(journal.capture('General warning', 'WARN', 'general'));
journal.setEnabled('diagnostics', true);
assert.ok(journal.capture('Diagnostic', 'DEBUG', 'diagnostics'));
let profilerSetting = null;
globalThis.ReclassifierPerformanceProfiler = { setEnabled: value => { profilerSetting = value; } };
journal.setEnabled('performance', false);
assert.equal(profilerSetting, false);
assert.equal(journal.capture('Perf suppressed', 'INFO', 'performance'), null);
journal.setEnabled('performance', true);
assert.equal(profilerSetting, true);
assert.ok(journal.capture('Perf', 'INFO', 'performance'));
assert.equal(journal.setEnabled('general', false), true);
assert.equal(journal.enabled('general'), false);
assert.equal(journal.capture('General disabled'), null);
assert.equal(journal.setEnabled('general', true), true);
assert.equal(journal.setEnabled('unknown', false), false);
assert.equal(journal.capture('Unknown class', 'INFO', 'unknown').category, 'general');
journal.clear();
assert.deepEqual(journal.entries(), []);
assert.equal(journal.operationSummary().totalOperations, 0);
assert.equal(journal.operationSummary().droppedEvents, 0);
const snapshotEmpty = journal.exportSnapshot('0.37.0');
assert.equal(snapshotEmpty.schemaVersion, 1);
assert.equal(snapshotEmpty.application, 'Reclassifier');
assert.equal(snapshotEmpty.applicationVersion, '0.37.0');
assert.equal(snapshotEmpty.retainedEventCount, 0);
assert.equal(snapshotEmpty.events.length, 0);
assert.equal(snapshotEmpty.capacity, 300);
assert.equal(snapshotEmpty.settings.performance, true);
assert.ok(Number.isFinite(Date.parse(snapshotEmpty.exportedAt)));
assert.equal(JSON.parse(JSON.stringify(snapshotEmpty)).events.length, 0);
for (let i = 0; i < 321; i++) journal.capture('event ' + i);
assert.equal(journal.entries().length, 300);
assert.equal(journal.entries()[0].message, 'event 21');
assert.equal(journal.entries().at(-1).message, 'event 320');
assert.ok(journal.lines()[0].includes('event 21'));
assert.equal(journal.select().length, 300);
assert.equal(journal.select({level:'ERROR'}).length, 0);
assert.equal(journal.select({category:'runtime'}).length, 0);
assert.equal(journal.select({query:'EVENT 3'}).length, 31);
assert.equal(journal.select({query:'event 320'}).length, 1);
assert.equal(journal.select({query:'not-in-log'}).length, 0);
assert.equal(journal.entries().length, 300, 'filtering must not mutate stored events');
assert.equal(journal.operationSummary().droppedEvents, 21);
assert.equal(journal.operationSummary().completeHistoryGuaranteed, false);
const exported = journal.exportSnapshot('0.37.0');
assert.equal(exported.events.length, 300);
assert.equal(exported.retainedEventCount, 300);
assert.equal(exported.events[0].message, 'event 21');
assert.equal(exported.events[0].category, 'general');
const singleGeneral = journal.exportCategorySnapshot('general', '0.37.0');
assert.equal(singleGeneral.retainedEventCount, 300);
assert.equal(singleGeneral.captureEnabled, true);
assert.equal(singleGeneral.countsByLevel.INFO, 300);
assert.equal(singleGeneral.events.length, 300);
assert.equal(journal.exportCategorySnapshot('invalid'), null);
assert.ok(!Object.hasOwn(exported.events[0], 'line'));
assert.deepEqual(Object.keys(exported.events[0]), ['timestamp', 'level', 'category', 'message']);
console.log('Diagnostic journal contract: OK');
