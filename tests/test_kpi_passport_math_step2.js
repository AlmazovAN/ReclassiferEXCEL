// Phase 2/4: human-readable KPI passports use native MathML (offline) and exact Calculator formula signatures.
'use strict';
const assert=require('node:assert/strict');
require('../src/js/app/reliability_dashboard_data.js');
require('../src/js/modules/itsm/mb_presence.js');
require('../src/js/kpi/source_facts.js');
for(const p of ['common','failures','equipment','labor','sla','classification','prb','ktg','index'])
  require('../src/js/kpi/preparation/'+p+'.js');
require('../src/js/kpi/calculator/common.js');
require('../src/js/kpi/calculator/definitions.js');
for(const p of ['vbr','ktg','sla','classification_quality','classification_quality_cgps','labor','problem_management'])
  require('../src/js/kpi/calculator/'+p+'/calculate.js');
require('../src/js/kpi/calculator/index.js');
require('../src/js/kpi/catalog/contracts.js');
require('../src/js/kpi/catalog/index.js');
require('../src/js/kpi/passport_math.js');
require('../src/js/kpi/passport_view.js');
const math=globalThis.ReclassifierKpiPassportMath;
const catalog=globalThis.ReclassifierKpiCatalog;
const passport=globalThis.ReclassifierKpiPassportView;
const calculated=catalog.list({calculationState:'implemented'});
assert.equal(calculated.length,16);
assert.equal(catalog.list().length,22);
assert.equal(math.ids.length,16);
assert.deepEqual(new Set(math.ids),new Set(calculated.map(x=>x.id)));
for(const entry of catalog.list()){
  const def=entry.definition;
  assert(def.fullTitle && typeof def.fullTitle==='string');
  assert(def.definition && typeof def.definition==='string');
  assert(def.purpose && typeof def.purpose==='string');
  const output=passport.renderContent(entry.id);
  assert(output.includes('id="kpi-passport-overview"'),entry.id+' has overview');
  assert(output.includes('<strong>Назначение:</strong>'),entry.id+' has compact definition');
  assert(output.includes('Единица измерения:'),entry.id);
  assert(output.includes('Направление улучшения:'),entry.id);
  assert(output.includes('Цель / порог:'),entry.id);
  assert(output.includes(def.fullTitle.replaceAll('&','&amp;')),entry.id+' full name');
  if(entry.calculation){
    assert(output.includes('id="kpi-passport-formula"'),entry.id);
    assert(output.includes('class="kpi-passport-math-document"'),entry.id);
    assert(output.includes('xmlns="http://www.w3.org/1998/Math/MathML"'),entry.id);
    assert(output.includes('<mrow>') && output.includes('<math'),entry.id+' MathML');
    assert(output.includes('Где:') && output.includes('Пример расчёта'),entry.id);
    assert(output.includes('Пример условный'),entry.id);
    if(['vbr','ktg','classification_quality','classification_quality_cgps'].includes(entry.id))assert(output.includes('Версия формулы'),entry.id);
    else assert(output.includes('Машинная запись и версия формулы'),entry.id);
    assert(output.includes(entry.calculation.formula.expression.replaceAll('>','&gt;')),entry.id+' raw machine formula');
    assert(!output.includes('Математическое представление требует сверки'),entry.id+' formula signature mismatch');
    assert(output.includes(['vbr','ktg','classification_quality','classification_quality_cgps'].includes(entry.id)?'Фактическая трассировка':'Показать расчёт'),entry.id+' existing trace intact');
  } else {
    assert(!output.includes('class="kpi-passport-math-document"'),entry.id);
    assert(!output.includes('Пример расчёта'),entry.id);
    assert(output.includes('Расчёт ещё не реализован'),entry.id);
  }
}
const vbr=passport.renderContent('vbr');
assert(vbr.includes('ВБР — вероятность безотказной работы'));
assert(vbr.includes('За три месяца зарегистрировано 10, 5 и 5 отказов'));
assert(vbr.includes('<mfrac>'));
assert(vbr.includes('<mn>5</mn>'));
assert(vbr.includes('<mn>100</mn>'));
assert(vbr.includes('<mn>3</mn>'));
assert(vbr.includes('93,33'));
assert(vbr.includes('Количество отчётных месяцев'));
assert(vbr.indexOf('kpi-passport-math-example') < vbr.indexOf('Многомесячный расчёт и фонд наблюдения'));
assert.doesNotMatch(vbr,/Техническая надёжность · vbr/);
assert(vbr.includes('повторных отказах одной единицы'));
assert(vbr.includes('Это не строгая статистическая вероятность') || vbr.includes('не строгая индивидуальная вероятность'));
assert(vbr.includes('<msub>'));
assert.match(vbr,/Многомесячный расчёт и фонд наблюдения/);
assert.match(vbr,/ед.·мес./);
assert(vbr.includes('93,33'));
assert(vbr.includes('Пример расчёта'));
assert.match(vbr,/ед.·мес./);
const ktgBreakdown=passport.renderContent('ktg');
assert.match(ktgBreakdown,/Состав продолжительности работ/);
assert.match(ktgBreakdown,/INC \+ TТО.факт \+ TТО.вн \+ Tпроч/);
assert.match(ktgBreakdown,/относится только к INC/);
const sla=passport.renderContent('sla');
assert(sla.includes('SLA — соблюдение соглашения об уровне сервиса'));
assert(sla.includes('<mn>9</mn>'));
assert(sla.includes('<mn>10</mn>'));
assert(sla.includes('<mn>90</mn>'));
const reactive=passport.renderContent('reactive_share');
assert(reactive.includes('<mn>40</mn>'));
assert(reactive.includes('<mn>10</mn>'));
assert(reactive.includes('<mn>100</mn>'));
assert(reactive.includes('<mn>50</mn>'));
const labor=passport.renderContent('total_labor');
assert(labor.includes('<mo>∑</mo>'));
assert(labor.includes('чел.-ч'));
assert(!labor.includes('<mfrac>'));
const noSnapshot=passport.renderContent('vbr',{snapshot:{}});
assert(noSnapshot.includes('Пример условный'));
assert(!noSnapshot.includes('Источник расчёта: пример'));
assert.equal(math.render('ktg').includes('<mfrac>'),true);
assert(Object.isFrozen(math));
assert(Object.isFrozen(catalog.get('vbr').definition));
console.log('KPI passport phase 2: native offline MathML, notation/examples for all 12 formulas, 18 descriptions, safe placeholders and VBR caveat OK');
