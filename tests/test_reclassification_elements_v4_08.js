'use strict';
const assert=require('node:assert/strict');
require('../src/js/modules/reclassification/classifier_index_v4.js');
require('../src/js/modules/reclassification/facts_v4.js');
require('../src/js/modules/reclassification/event_v4.js');
require('../src/js/modules/reclassification/objects_v4.js');
require('../src/js/modules/reclassification/elements_v4.js');
const obj=globalThis.ReclassifierObjectAssessmentV4;
const api=globalThis.ReclassifierElementAssessmentV4;
const records=[['СВР','Кабель камеры','Обрыв','Не установлена'],['СВР','Камера','Отказ','Не установлена'],['СВР','Блок питания','Отказ','Не установлена'],['СВН','Кабель камеры','Обрыв','Не установлена']];
const context=obj.fromPreparedRecords(records);
function evaluate(text,ctx=context,description='Не работает изображение'){
 const event=globalThis.ReclassifierEventAssessmentV4.analyze({number:'INC-1',description,closureNote:text});
 const objects=obj.analyze(event,ctx);
 return {objects,result:api.analyze(objects,ctx)};
}
let x=evaluate('Обнаружен обрыв кабеля камеры СВР.');
assert.equal(x.objects.status,'SELECTED');
assert.equal(x.result.status,'SELECTED');
assert.equal(x.result.selectedElement,'Кабель камеры');
assert.deepEqual(x.result.candidatePath,['СВР','Кабель камеры',null,null]);
assert.equal(x.result.readyForApply,false);
assert.equal(x.result.independentlyVerified,false);
assert.equal(x.result.evidence.targets[0].text,'кабеля камеры');
assert(Object.isFrozen(x.result));
assert(Object.isFrozen(x.result.evidence.targets));
assert.equal(evaluate('Обнаружен обрыв кабеля камеры.').result.status,'BLOCKED_BY_OBJECT');
assert.equal(evaluate('Заменён блок питания.').result.selectedElement,null);
assert.equal(evaluate('Возможно неисправна камера.').result.selectedElement,null);
assert.equal(evaluate('Обнаружен обрыв кабеля камеры СВР. Выявлен отказ камеры СВР.').result.selectedElement,null);
const equipmentOnly={status:'SELECTED',selectedEquipment:'СВР',failedObject:{level:'equipment',canonical:'СВР'},effectiveFailureState:'FAILURE',targets:[]};
assert.equal(api.analyze(equipmentOnly,context).status,'UNRESOLVED');
assert.equal(api.analyze(equipmentOnly,context).elementCandidates.length,3);
const forged={...equipmentOnly,failedObject:{level:'element',canonical:'Неизвестный модуль'}};
assert.equal(api.analyze(forged,context).status,'NOT_IN_CLASSIFIER');
assert.equal(api.analyze({...equipmentOnly,status:'NOT_APPLICABLE',effectiveFailureState:'NON_FAILURE'},context).status,'NOT_APPLICABLE');
assert.throws(()=>api.analyze({},{}),/INDEX_REQUIRED/);
const before=JSON.stringify(x.objects),dictionaryBefore=JSON.stringify(records);
api.analyze(x.objects,context);
assert.equal(JSON.stringify(x.objects),before);
assert.equal(JSON.stringify(records),dictionaryBefore);
const guarded={...x.objects};
for(const label of ['expertPath','sourceElement','legacyResult'])Object.defineProperty(guarded,label,{get(){throw Error('forbidden label');}});
assert.equal(api.analyze(guarded,context).selectedElement,'Кабель камеры');
console.log('V4-08: element evidence, classifier constraints, ambiguity, no inferred element, independent and immutable PASS');
